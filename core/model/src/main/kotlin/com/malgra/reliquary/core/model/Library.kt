package com.malgra.reliquary.core.model

import kotlin.time.Duration
import kotlin.time.Instant

/**
 * A video in the Tube Archivist library. IDs are YouTube IDs. URLs are absolute,
 * resolved against the signed-in server. Watch state is the server's as of the
 * last refresh.
 */
data class Video(
    val id: String,
    val title: String,
    val channelId: String,
    val channelName: String,
    val description: String?,
    val type: VideoType,
    val duration: Duration,
    /** When the video was published on YouTube; null if the server sent no date. */
    val published: Instant?,
    /** When the server downloaded it into the archive. */
    val addedToArchive: Instant?,
    val mediaUrl: String,
    val mediaSizeBytes: Long,
    val thumbnailUrl: String?,
    val watched: Boolean,
    val position: Duration,
    /** True while a position or watched change made here hasn't reached the server. */
    val syncPending: Boolean = false,
    /** Null when the video isn't downloaded or being downloaded. */
    val download: DownloadStatus? = null,
    val subtitles: List<Subtitle> = emptyList(),
    /** SponsorBlock segments the player can skip, in order; empty if the server has none. */
    val sponsorSegments: List<SponsorSegment> = emptyList(),
) {
    val isDownloaded: Boolean get() = download == DownloadStatus.Completed

    /** 0..1, or null when there is no position to show. */
    val progress: Float?
        get() = if (watched || position <= Duration.ZERO || duration <= Duration.ZERO) {
            null
        } else {
            (position / duration).toFloat().coerceIn(0f, 1f)
        }

    val remaining: Duration
        get() = (duration - position).coerceAtLeast(Duration.ZERO)
}

/** A subtitle track the server has for a video. [url] is absolute. */
data class Subtitle(
    /** BCP 47-ish code from YouTube, e.g. "en" or "pt-BR". */
    val language: String,
    /** The name the server gives it, e.g. "English". */
    val name: String,
    val url: String,
    /** True for YouTube's automatic captions. */
    val autoGenerated: Boolean,
) {
    /** Unique within a video; names the track in the player and the downloaded file. */
    val key: String get() = "$language.${if (autoGenerated) "auto" else "user"}"
}

/** A part of a video SponsorBlock marks as skippable. [category] is SponsorBlock's, e.g. "sponsor" or "intro". */
data class SponsorSegment(val start: Duration, val end: Duration, val category: String) {
    val isSponsor: Boolean get() = category == "sponsor"
}

/** A YouTube comment Tube Archivist saved with a video. */
data class Comment(
    val id: String,
    val author: String,
    val text: String,
    val published: Instant?,
    val likeCount: Int?,
    /** Written by the video's own channel. */
    val byUploader: Boolean,
    /** Hearted by the video's channel. */
    val favorited: Boolean,
    /** Answers to this comment, oldest first. */
    val replies: List<Comment> = emptyList(),
)

/** Tube Archivist's `vid_type`, which matches the YouTube channel tabs. */
enum class VideoType(val apiValue: String) {
    Videos("videos"),
    Streams("streams"),
    Shorts("shorts");

    companion object {
        fun fromApi(value: String?): VideoType = entries.firstOrNull { it.apiValue == value } ?: Videos
    }
}

data class Channel(
    val id: String,
    val name: String,
    val description: String?,
    val thumbnailUrl: String?,
    val bannerUrl: String?,
    val subscribed: Boolean,
    val subscriberCount: Long,
    /** Which tabs the archive has content for; null until the channel is opened once. */
    val tabs: ChannelTabs?,
)

data class ChannelTabs(
    val videos: Boolean,
    val streams: Boolean,
    val shorts: Boolean,
    val playlists: Boolean,
)

data class Playlist(
    val id: String,
    val name: String,
    val channelId: String?,
    val channelName: String?,
    val description: String?,
    val thumbnailUrl: String?,
    val subscribed: Boolean,
    /** Entries in the YouTube playlist. */
    val entryCount: Int,
    /** Entries the server has archived. */
    val archivedCount: Int,
)

/** Filter for a channel's video list. */
enum class WatchFilter { All, Unwatched, OnDevice }

/** Why loading failed, in terms a screen can explain. */
enum class LoadError { Offline, ServerError, Unexpected }

/** Combined search results across the library. */
data class SearchResults(
    val videos: List<Video>,
    val channels: List<Channel>,
    val playlists: List<Playlist>,
    /** True when the server couldn't be reached and these came from the cache on this device. */
    val fromCache: Boolean,
) {
    val isEmpty: Boolean get() = videos.isEmpty() && channels.isEmpty() && playlists.isEmpty()

    companion object {
        val Empty = SearchResults(emptyList(), emptyList(), emptyList(), fromCache = false)
    }
}

/**
 * Playback position as the app knows it. The server stores no timestamp for
 * position, so the client tracks when it last changed locally and whether that
 * change still has to be pushed.
 */
data class WatchProgress(
    val videoId: String,
    val position: Duration,
    val updatedAtEpochMillis: Long,
    val pendingSync: Boolean,
)

enum class DownloadStatus { Queued, Downloading, Paused, Completed, Failed }

/** A video saved, or being saved, to this device. */
data class Download(
    val videoId: String,
    val status: DownloadStatus,
    val bytesDownloaded: Long,
    /** 0 when not known yet. */
    val totalBytes: Long,
) {
    /** 0..1, or null while the size isn't known. */
    val fraction: Float?
        get() = if (totalBytes > 0) (bytesDownloaded.toFloat() / totalBytes).coerceIn(0f, 1f) else null
}

/** A download with its video, for the Downloads tab. [video] is null if it's no longer cached. */
data class DownloadedVideo(val download: Download, val video: Video?)

/** Keeps a channel's or playlist's videos downloaded automatically. */
data class KeepOfflineRule(
    val kind: Kind,
    val sourceId: String,
    val name: String,
    val thumbnailUrl: String?,
    /** How many of the newest videos to keep; null keeps a whole playlist. */
    val keepCount: Int?,
    val unwatchedOnly: Boolean,
    val wifiOnly: Boolean,
    val removeWhenWatched: Boolean,
) {
    enum class Kind { Channel, Playlist }

    val id: String get() = idFor(kind, sourceId)

    companion object {
        const val DEFAULT_KEEP_COUNT = 5
        const val MAX_KEEP_COUNT = 50

        fun idFor(kind: Kind, sourceId: String) = "${kind.name.lowercase()}:$sourceId"

        /** The sheet's starting values for a source with no rule yet, as in the mockup. */
        fun defaultFor(kind: Kind, sourceId: String, name: String, thumbnailUrl: String?) = KeepOfflineRule(
            kind = kind,
            sourceId = sourceId,
            name = name,
            thumbnailUrl = thumbnailUrl,
            keepCount = if (kind == Kind.Playlist) null else DEFAULT_KEEP_COUNT,
            unwatchedOnly = true,
            wifiOnly = true,
            removeWhenWatched = true,
        )
    }
}
